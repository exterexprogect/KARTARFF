function getApiName(regionName) {
    return API_NAME_MAP[regionName] || regionName.replace(' обл.', '').replace(' край', '');
}

function getDisplayName(regionName) {
    if (REGION_DISPLAY.has(regionName)) {
        return REGION_DISPLAY.get(regionName);
    }
    if (regionName.endsWith(' обл.')) {
        const main = regionName.replace(' обл.', '');
        return [main, 'обл.'];
    }
    if (regionName.endsWith(' край')) {
        const main = regionName.replace(' край', '');
        return [main, 'край'];
    }
    return [regionName, ''];
}
